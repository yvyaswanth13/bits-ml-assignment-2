import streamlit as st
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import joblib
import os
from sklearn.metrics import accuracy_score, roc_auc_score, precision_score, recall_score, f1_score, matthews_corrcoef, confusion_matrix, classification_report

# Page Config
st.set_page_config(page_title="ML Classifier Evaluation Hub", layout="wide", initial_sidebar_state="expanded")

st.title("📊 Machine Learning Classification Model Evaluation App")
st.markdown("This interactive interface evaluates pre-trained classification models on user-provided evaluation data without retraining.")

# Sidebar Controls
st.sidebar.header("🛠️ Controls & Configuration")

# Feature: Dataset upload option
uploaded_file = st.sidebar.file_uploader("Upload Test Dataset (CSV)", type=["csv"], help="Upload a CSV containing features and a 'target' column.")

# Feature: Model selection dropdown
model_mapping = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree Classifier": "decision_tree.joblib",
    "K-Nearest Neighbor Classifier": "knn.joblib",
    "Naive Bayes Classifier": "naive_bayes.joblib",
    "Support Vector Machine": "svm.joblib"
}
selected_model_name = st.sidebar.selectbox("Choose Classification Model", list(model_mapping.keys()))

# Execution logic
if uploaded_file is not None:
    # Load dataset safely
    data = pd.read_csv(uploaded_file)
    
    if 'target' not in data.columns:
        st.error("❌ The dataset must contain a column named exactly 'target'.")
    else:
        # Separate features and target
        X_test = data.drop(columns=['target'])
        y_test = data['target']
        
        # Load Model
        model_path = os.path.join("model", model_mapping[selected_model_name])
        
        if not os.path.exists(model_path):
            st.error(f"❌ Saved model file not found at `{model_path}`. Run training script first.")
        else:
            model = joblib.load(model_path)
            
            # Predict
            y_pred = model.predict(X_test)
            
            # Handle probability estimation for AUC calculation
            if hasattr(model, "predict_proba"):
                y_prob = model.predict_proba(X_test)[:, 1]
            elif hasattr(model, "decision_function"):
                y_prob = model.decision_function(X_test)
            else:
                y_prob = y_pred
            
            # Calculate metrics
            acc = accuracy_score(y_test, y_pred)
            try:
                auc = roc_auc_score(y_test, y_prob)
            except ValueError:
                auc = 0.5  # Fallback for unexpected shapes or edge cases
            prec = precision_score(y_test, y_pred, zero_division=0)
            rec = recall_score(y_test, y_pred, zero_division=0)
            f1 = f1_score(y_test, y_pred, zero_division=0)
            mcc = matthews_corrcoef(y_test, y_pred)
            
            # Layout splits: Metrics vs Visualization
            col1, col2 = st.columns([1, 1])
            
            with col1:
                st.subheader(f"📈 Evaluation Metrics: {selected_model_name}")
                
                # Visual Metric Cards
                m_col1, m_col2, m_col3 = st.columns(3)
                m_col1.metric("Accuracy", f"{acc:.4f}")
                m_col2.metric("AUC Score", f"{auc:.4f}")
                m_col3.metric("Precision", f"{prec:.4f}")
                
                m_col4, m_col5, m_col6 = st.columns(3)
                m_col4.metric("Recall", f"{rec:.4f}")
                m_col5.metric("F1-Score", f"{f1:.4f}")
                m_col6.metric("MCC Score", f"{mcc:.4f}")
                
                # Classification Report Block
                st.subheader("📋 Classification Report")
                report_dict = classification_report(y_test, y_pred, output_dict=True, zero_division=0)
                st.dataframe(pd.DataFrame(report_dict).transpose().style.format("{:.4f}"))
                
            with col2:
                st.subheader("🎯 Confusion Matrix Visualizer")
                cm = confusion_matrix(y_test, y_pred)
                
                fig, ax = plt.subplots(figsize=(6, 5))
                sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', 
                            xticklabels=['Negative (0)', 'Positive (1)'], 
                            yticklabels=['Negative (0)', 'Positive (1)'], ax=ax)
                plt.ylabel('Actual Label')
                plt.xlabel('Predicted Label')
                plt.tight_layout()
                st.pyplot(fig)
                
else:
    st.info("💡 Please upload the `test_data.csv` file generated by your pipeline in the sidebar menu to begin evaluation.")
